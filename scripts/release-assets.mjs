import { readFile, readdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const pkg = JSON.parse(await readFile('package.json','utf8'));
if (process.env.RELEASE_TAG !== `v${pkg.version}` || !pkg.version.includes('-alpha.')) throw new Error('Tag must match the alpha package version');
const names = (await readdir('release-assets')).filter(n=>/\.(dmg|exe|AppImage|deb)$/.test(n)).sort();
const expected = [`Made-Mail-${pkg.version}-mac-arm64.dmg`,`Made-Mail-${pkg.version}-mac-x64.dmg`,`Made-Mail-${pkg.version}-win-x64.exe`,`Made-Mail-${pkg.version}-linux-x64.AppImage`,`Made-Mail-${pkg.version}-linux-x64.deb`].sort();
if (JSON.stringify(names)!==JSON.stringify(expected)) throw new Error(`Expected five platform installers, got ${names.join(', ')}`);
const sums = [];
for (const name of names) sums.push(`${createHash('sha256').update(await readFile(`release-assets/${name}`)).digest('hex')}  ${name}`);
await writeFile('release-assets/SHA256SUMS.txt',sums.join('\n')+'\n');
